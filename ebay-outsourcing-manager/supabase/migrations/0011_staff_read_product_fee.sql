-- ============================================================
-- eBay外注管理ツール スタッフ画面の梱包報酬の表示ズレ修正
-- SupabaseのSQL Editorにこのファイル全体を貼り付けて「Run」してください。
--
-- 【原因】
-- 梱包報酬は「商品ごとの上書き（product_fees）→ なければカテゴリー標準報酬」
-- の順で決まる。しかし product_fees はこれまで管理者しか読めなかったため、
-- スタッフ画面は上書き額を取得できず、常にカテゴリー標準報酬を表示していた。
-- 例: カテゴリーが Audio（標準1,500円）のまま、商品ごとの報酬を500円に
--     設定すると、管理者画面は500円、スタッフ画面は1,500円と食い違う。
--
-- 【対応】
-- スタッフが「自分の担当商品の梱包報酬」だけを読めるようにする。
-- 金額はもともとスタッフ画面に表示している情報（本人の報酬額）であり、
-- 担当外の商品や他スタッフの商品は引き続き読めない。
-- 変更・追加・削除は従来どおり管理者のみ。
-- ============================================================

-- 既存の "product_fees_admin_only"（for all）はそのまま残す。
-- select だけをスタッフにも許可するポリシーを追加する。
drop policy if exists "product_fees_staff_select" on public.product_fees;
create policy "product_fees_staff_select" on public.product_fees
  for select using (public.is_assigned(product_id));
